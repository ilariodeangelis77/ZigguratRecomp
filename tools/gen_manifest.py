"""Generate port/src/core/ManifestData.inc: name/size/SHA-256 of every file the port
imports from a ZiGGURAT IPA (hashes only, no content).
Usage: python -I tools/gen_manifest.py <ZiGGURAT.ipa> <out.inc>
Selection mirrors tools/extract_assets.py (+ iTunesArtwork at the IPA root)."""
import hashlib, plistlib, sys, zipfile, io

SKIP = ("OFResources_Universal.bundle", "FBDialog.bundle", "_CodeSignature")
APP = "Payload/Zig2.app/"


def main(ipa, out):
    rows = []
    version = "?"
    with zipfile.ZipFile(ipa) as z:
        info = plistlib.load(io.BytesIO(z.read(APP + "Info.plist")))
        version = info.get("CFBundleShortVersionString", "?")
        bundle = info.get("CFBundleIdentifier", "?")
        for zi in z.infolist():
            n = zi.filename
            if n.endswith("/"):
                continue
            if n == "iTunesArtwork":
                rel, optional = "iTunesArtwork", 1
            elif n.startswith(APP):
                rel = n[len(APP):]
                optional = 0
                if any(s in rel for s in SKIP):
                    continue
                low = rel.lower()
                base = rel.split("/")[-1]
                if not (low.endswith((".png", ".wav", ".mp3", ".ttf")) or base == "Localizable.strings"):
                    continue
            else:
                continue
            data = z.read(zi)
            rows.append((rel, len(data), hashlib.sha256(data).hexdigest(), optional))
    rows.sort()
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by tools/gen_manifest.py - do not edit.\n")
        f.write("// Bundle %s version %s: %d files (hashes only, no game content).\n" % (bundle, version, len(rows)))
        f.write('static const char* kManifestVersion = "%s";\n' % version)
        f.write('static const char* kManifestBundleId = "%s";\n' % bundle)
        f.write("static const ManifestEntry kManifestEntries[] = {\n")
        for rel, size, sha, opt in rows:
            f.write('    {"%s", %d, "%s", %s},\n' % (rel.replace("\\", "\\\\").replace('"', '\\"'), size, sha,
                                                    "true" if opt else "false"))
        f.write("};\n")
    print("entries:", len(rows), "version:", version)


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
